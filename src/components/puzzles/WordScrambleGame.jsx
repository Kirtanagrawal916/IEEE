import React, { useState, useEffect, useMemo, useCallback } from 'react';
import { 
  Sparkles, 
  RotateCcw, 
  Lightbulb, 
  Trophy, 
  CheckCircle2, 
  HelpCircle, 
  Volume2, 
  VolumeX, 
  ChevronRight,
  Flame,
  Shuffle,
  ArrowRight,
  Brain
} from 'lucide-react';
import { playPop, playSnap, playErrorTone, playChimeVictory } from '../../utils/puzzleAudio';

const SCRAMBLE_WORDS = [
  // Coding & Technology
  { word: 'CODE', category: 'Coding & Tech', hint: 'Instructions written for a computer to execute' },
  { word: 'REACT', category: 'Coding & Tech', hint: 'Popular declarative JavaScript UI component library' },
  { word: 'PYTHON', category: 'Coding & Tech', hint: 'Versatile programming language named after comedy troupe' },
  { word: 'SERVER', category: 'Coding & Tech', hint: 'Computers that host backend APIs and databases' },
  { word: 'DATABASE', category: 'Coding & Tech', hint: 'Organized electronic collection of structured records' },
  { word: 'ALGORITHM', category: 'Coding & Tech', hint: 'Step-by-step problem-solving computational procedure' },
  { word: 'DEBUG', category: 'Coding & Tech', hint: 'The process of finding and fixing software bugs' },
  
  // Business & Finance
  { word: 'STARTUP', category: 'Business & Growth', hint: 'Fast-growing new venture building an innovative product' },
  { word: 'REVENUE', category: 'Business & Growth', hint: 'Total income generated by business operations' },
  { word: 'PROFIT', category: 'Business & Growth', hint: 'Financial gain after subtracting all costs and taxes' },
  { word: 'INVEST', category: 'Business & Growth', hint: 'Allocating capital with expectation of future returns' },
  { word: 'STRATEGY', category: 'Business & Growth', hint: 'High-level plan of action designed to achieve long-term goals' },

  // Freelancing & Communication
  { word: 'CLIENT', category: 'Freelance & Career', hint: 'Person or organization paying for your professional services' },
  { word: 'PITCH', category: 'Freelance & Career', hint: 'Short presentation proposing an idea or service to a buyer' },
  { word: 'CONTRACT', category: 'Freelance & Career', hint: 'Legally binding agreement outlining gig deliverables' },
  { word: 'PORTFOLIO', category: 'Freelance & Career', hint: 'Curated showcase of your best verified projects' },
  { word: 'DELIVER', category: 'Freelance & Career', hint: 'Handing over finished work meeting client milestones' },
  
  // Design & Media
  { word: 'CANVA', category: 'Design & Creative', hint: 'Drag-and-drop graphic design tool for social posts' },
  { word: 'LAYOUT', category: 'Design & Creative', hint: 'Arrangement of visual elements on a page or screen' },
  { word: 'VECTOR', category: 'Design & Creative', hint: 'Scalable graphic artwork based on mathematical curves' },
  { word: 'TYPOGRAPHY', category: 'Design & Creative', hint: 'The art and technique of arranging letters and fonts' },
];

export default function WordScrambleGame({ onGameWin, soundEnabled = true, onToggleSound }) {
  const [currentIndex, setCurrentIndex] = useState(0);
  const [scrambledLetters, setScrambledLetters] = useState([]); // Array of { id, char }
  const [answerSlots, setAnswerSlots] = useState([]); // Array of { id, char } | null
  const [showHint, setShowHint] = useState(false);
  const [streak, setStreak] = useState(0);
  const [score, setScore] = useState(0);
  const [seconds, setSeconds] = useState(0);
  const [isTimerRunning, setIsTimerRunning] = useState(false);
  const [hasWonCurrent, setHasWonCurrent] = useState(false);
  const [feedback, setFeedback] = useState(null); // 'correct' | 'wrong' | null

  const currentPuzzle = SCRAMBLE_WORDS[currentIndex];

  // Helper to shuffle letters ensuring it's not identical to original word
  const shuffleWord = useCallback((word) => {
    const letters = word.split('').map((char, index) => ({ id: `letter-${index}-${char}-${Math.random()}`, char }));
    let shuffled = [...letters];
    let attempts = 0;
    while (shuffled.map(l => l.char).join('') === word && attempts < 10) {
      shuffled.sort(() => Math.random() - 0.5);
      attempts++;
    }
    return shuffled;
  }, []);

  // Initialize current word
  const loadWord = useCallback((index) => {
    const puzzle = SCRAMBLE_WORDS[index];
    const letters = shuffleWord(puzzle.word);
    setScrambledLetters(letters);
    setAnswerSlots(new Array(puzzle.word.length).fill(null));
    setShowHint(false);
    setHasWonCurrent(false);
    setFeedback(null);
    setSeconds(0);
    setIsTimerRunning(true);
  }, [shuffleWord]);

  useEffect(() => {
    loadWord(currentIndex);
  }, [currentIndex, loadWord]);

  // Timer
  useEffect(() => {
    let timer = null;
    if (isTimerRunning && !hasWonCurrent) {
      timer = setInterval(() => setSeconds(s => s + 1), 1000);
    }
    return () => clearInterval(timer);
  }, [isTimerRunning, hasWonCurrent]);

  // Handle letter click from bank into answer
  const handleSelectLetter = (letterItem) => {
    if (hasWonCurrent) return;
    const firstEmptyIndex = answerSlots.findIndex(slot => slot === null);
    if (firstEmptyIndex === -1) return;

    if (soundEnabled) playPop();

    const newSlots = [...answerSlots];
    newSlots[firstEmptyIndex] = letterItem;
    setAnswerSlots(newSlots);

    setScrambledLetters(prev => prev.filter(l => l.id !== letterItem.id));
  };

  // Handle clicking letter in answer slots to return it to bank
  const handleRemoveLetter = (slotIndex) => {
    if (hasWonCurrent) return;
    const item = answerSlots[slotIndex];
    if (!item) return;

    if (soundEnabled) playSnap();

    const newSlots = [...answerSlots];
    newSlots[slotIndex] = null;
    setAnswerSlots(newSlots);

    setScrambledLetters(prev => [...prev, item]);
    setFeedback(null);
  };

  // Check if answer is complete and verify
  useEffect(() => {
    if (hasWonCurrent) return;
    const isFull = answerSlots.length > 0 && answerSlots.every(slot => slot !== null);
    if (!isFull) return;

    const assembledWord = answerSlots.map(s => s.char).join('');
    if (assembledWord === currentPuzzle.word) {
      // Victory! Instant feedback with zero latency
      setFeedback('correct');
      setHasWonCurrent(true);
      setIsTimerRunning(false);
      if (soundEnabled) playChimeVictory();

      const earnedPts = Math.max(30, 60 - Math.floor(seconds / 2)) + (streak * 10);
      setScore(s => s + earnedPts);
      setStreak(st => st + 1);

      if (onGameWin) {
        onGameWin({
          game: 'word-scramble',
          title: `Word Scramble: ${currentPuzzle.word}`,
          points: earnedPts,
          badge: streak >= 2 ? '🔤 Vocabulary Champion' : '🔤 Word Scramble',
          timeTaken: seconds,
          moves: currentPuzzle.word.length
        });
      }
    } else {
      setFeedback('wrong');
      if (soundEnabled) playErrorTone();
    }
  }, [answerSlots, currentPuzzle, streak, seconds, soundEnabled, onGameWin, hasWonCurrent]);

  // Keyboard typing support & instant navigation
  useEffect(() => {
    const handleKeyDown = (e) => {
      if (hasWonCurrent) {
        if (e.key === 'Enter' || e.key === ' ') {
          e.preventDefault();
          handleNextWord();
        }
        return;
      }
      const key = e.key.toUpperCase();

      if (key === 'BACKSPACE') {
        // Remove last filled slot
        for (let i = answerSlots.length - 1; i >= 0; i--) {
          if (answerSlots[i] !== null) {
            handleRemoveLetter(i);
            break;
          }
        }
        return;
      }

      // Check if typed letter exists in available letters
      const availableIndex = scrambledLetters.findIndex(l => l.char === key);
      if (availableIndex !== -1) {
        handleSelectLetter(scrambledLetters[availableIndex]);
      }
    };

    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [scrambledLetters, answerSlots, hasWonCurrent]);

  const handleNextWord = () => {
    setCurrentIndex(prev => (prev + 1) % SCRAMBLE_WORDS.length);
  };

  const handleReshuffle = () => {
    if (hasWonCurrent) return;
    // Return all back to scrambled
    const all = [...scrambledLetters, ...answerSlots.filter(Boolean)];
    all.sort(() => Math.random() - 0.5);
    setScrambledLetters(all);
    setAnswerSlots(new Array(currentPuzzle.word.length).fill(null));
    setFeedback(null);
    if (soundEnabled) playSnap();
  };

  return (
    <div className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-purple-500/30 rounded-3xl p-6 sm:p-8 space-y-8 shadow-xl">
      
      {/* Header Info Bar */}
      <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 border-b border-slate-100 dark:border-slate-800 pb-5">
        <div>
          <div className="flex items-center gap-2">
            <span className="px-2.5 py-0.5 rounded-full text-[11px] font-extrabold uppercase bg-indigo-100 dark:bg-indigo-950/70 text-indigo-700 dark:text-indigo-300 border border-indigo-200 dark:border-indigo-800/50">
              {currentPuzzle.category}
            </span>
            <span className="text-xs font-bold text-slate-500 dark:text-slate-400">
              Word {currentIndex + 1} of {SCRAMBLE_WORDS.length}
            </span>
          </div>
          <h2 className="text-2xl font-black text-slate-900 dark:text-white mt-1">
            Word Scramble Challenge 🔤
          </h2>
        </div>

        {/* Live HUD Stats */}
        <div className="flex items-center gap-3">
          <div className="flex items-center gap-1.5 px-3.5 py-1.5 rounded-xl bg-amber-50 dark:bg-amber-950/40 border border-amber-200 dark:border-amber-800/50 text-amber-700 dark:text-amber-300 text-xs font-extrabold">
            <Trophy className="w-4 h-4 text-amber-500" />
            <span>{score} PTS</span>
          </div>

          <div className="flex items-center gap-1.5 px-3 py-1.5 rounded-xl bg-purple-50 dark:bg-purple-950/40 border border-purple-200 dark:border-purple-800/50 text-purple-700 dark:text-purple-300 text-xs font-extrabold">
            <Flame className="w-4 h-4 text-pink-500" />
            <span>Streak: {streak}🔥</span>
          </div>

          <div className="text-xs font-mono font-bold text-slate-500 dark:text-slate-400 px-2">
            ⏱ {seconds}s
          </div>
        </div>
      </div>

      {/* Main Game Stage */}
      <div className="max-w-xl mx-auto space-y-6 text-center">
        
        {/* Answer Slots */}
        <div className="space-y-2">
          <span className="text-xs font-bold uppercase tracking-wider text-slate-400 dark:text-slate-500 block">
            Click letter to place or backspace to remove
          </span>

          <div className="flex items-center justify-center gap-2 sm:gap-3 flex-wrap min-h-[4rem]">
            {answerSlots.map((slot, idx) => (
              <button
                key={`slot-${idx}`}
                type="button"
                onClick={() => handleRemoveLetter(idx)}
                disabled={!slot || hasWonCurrent}
                className={`w-12 h-14 sm:w-14 sm:h-16 rounded-2xl border-2 flex items-center justify-center text-xl sm:text-2xl font-black transition-colors cursor-pointer ${
                  slot
                    ? feedback === 'correct'
                      ? 'bg-emerald-500 border-emerald-600 text-white shadow-sm'
                      : feedback === 'wrong'
                      ? 'bg-rose-500 border-rose-600 text-white'
                      : 'bg-indigo-600 border-indigo-700 text-white shadow-sm'
                    : 'bg-slate-100 dark:bg-slate-800/80 border-dashed border-slate-300 dark:border-slate-700 text-transparent hover:border-purple-400'
                }`}
              >
                {slot?.char || ''}
              </button>
            ))}
          </div>
        </div>

        {/* Feedback message */}
        {feedback === 'wrong' && (
          <p className="text-sm font-bold text-rose-500 animate-fade-in">
            Not quite! Click letters to return them or reshuffle.
          </p>
        )}

        {feedback === 'correct' && (
          <div className="bg-emerald-50 dark:bg-emerald-950/40 border border-emerald-300 dark:border-emerald-800/50 rounded-2xl p-4 text-emerald-800 dark:text-emerald-200 animate-fade-in space-y-1">
            <div className="flex items-center justify-center gap-1.5 font-black text-base">
              <CheckCircle2 className="w-5 h-5 text-emerald-500" />
              <span>Correct! The word is "{currentPuzzle.word}"!</span>
            </div>
            <p className="text-xs text-emerald-700 dark:text-emerald-300 font-medium">
              +{Math.max(30, 60 - Math.floor(seconds / 2)) + (streak * 10)} Skill Points awarded!
            </p>
          </div>
        )}

        {/* Letter Bank to select from */}
        <div className="p-6 bg-slate-50 dark:bg-slate-800/50 border border-slate-200 dark:border-slate-800 rounded-3xl space-y-3">
          <span className="text-xs font-bold text-slate-500 dark:text-slate-400 block uppercase tracking-wider">
            Available Scrambled Letters
          </span>

          <div className="flex items-center justify-center gap-2.5 sm:gap-3 flex-wrap min-h-[3.5rem]">
            {scrambledLetters.length === 0 && !hasWonCurrent && (
              <span className="text-xs font-semibold text-slate-400">All letters placed!</span>
            )}
            {scrambledLetters.map((item) => (
              <button
                key={item.id}
                type="button"
                onClick={() => handleSelectLetter(item)}
                className="w-11 h-13 sm:w-13 sm:h-14 rounded-2xl bg-white dark:bg-slate-700 border border-slate-300 dark:border-slate-600 text-slate-800 dark:text-white font-extrabold text-lg sm:text-xl shadow-sm hover:border-indigo-500 hover:shadow-md hover:-translate-y-0.5 active:translate-y-0 transition-all cursor-pointer"
              >
                {item.char}
              </button>
            ))}
          </div>
        </div>

        {/* Hint Box */}
        <div className="text-center">
          {showHint ? (
            <div className="inline-block px-4 py-2 rounded-2xl bg-amber-50 dark:bg-amber-950/40 border border-amber-300 dark:border-amber-700/50 text-xs font-bold text-amber-800 dark:text-amber-200 animate-fade-in">
              💡 <strong>Clue:</strong> {currentPuzzle.hint}
            </div>
          ) : (
            <button
              type="button"
              onClick={() => setShowHint(true)}
              className="inline-flex items-center gap-1.5 text-xs font-bold text-purple-600 dark:text-purple-400 hover:text-purple-700 cursor-pointer"
            >
              <Lightbulb className="w-4 h-4 text-amber-500" />
              <span>Need a clue? Tap for hint</span>
            </button>
          )}
        </div>

        {/* Control Buttons */}
        <div className="flex items-center justify-center gap-3 pt-2">
          <button
            type="button"
            onClick={handleReshuffle}
            disabled={hasWonCurrent}
            className="px-4 py-2.5 rounded-2xl border border-slate-300 dark:border-slate-700 text-xs font-bold text-slate-700 dark:text-slate-300 hover:bg-slate-100 dark:hover:bg-slate-800 transition-all cursor-pointer flex items-center gap-1.5"
          >
            <Shuffle className="w-4 h-4" />
            <span>Reshuffle</span>
          </button>

          <button
            type="button"
            onClick={() => loadWord(currentIndex)}
            className="px-4 py-2.5 rounded-2xl border border-slate-300 dark:border-slate-700 text-xs font-bold text-slate-700 dark:text-slate-300 hover:bg-slate-100 dark:hover:bg-slate-800 transition-all cursor-pointer flex items-center gap-1.5"
          >
            <RotateCcw className="w-4 h-4" />
            <span>Reset Word</span>
          </button>

          {hasWonCurrent && (
            <button
              type="button"
              onClick={handleNextWord}
              className="px-6 py-2.5 rounded-2xl bg-gradient-to-r from-purple-600 to-indigo-600 text-white text-xs font-extrabold shadow-md hover:from-purple-500 hover:to-indigo-500 transition-all cursor-pointer flex items-center gap-1.5"
            >
              <span>Next Scramble</span>
              <span className="text-[10px] opacity-75 font-normal">(Enter ↵)</span>
              <ArrowRight className="w-4 h-4" />
            </button>
          )}
        </div>

      </div>

    </div>
  );
}
